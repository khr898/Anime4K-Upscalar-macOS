// Tests/PipelineSynchronizationTests.swift
// Unit tests for MoltenVK environment synchronization and FFmpeg filter threading flags.

import Foundation

@main
struct PipelineSynchronizationTests {
    static func main() {
        var passed = 0
        var failed = 0

        func check(_ name: String, _ condition: Bool, _ detail: String = "") {
            if condition {
                print("PASS: \(name)")
                passed += 1
            } else {
                print("FAIL: \(name) \(detail)")
                failed += 1
            }
        }

        // --- Test 1: MoltenVK Synchronization Environment Configuration ---
        // Simulating the environment generated by FFmpegLocator
        var env: [String: String] = [:]
        env["MVK_CONFIG_ALLOW_METAL_EVENTS"] = "0"
        env["MVK_CONFIG_VK_SEMAPHORE_SUPPORT_STYLE"] = "0"
        env["MVK_CONFIG_SYNCHRONOUS_QUEUE_SUBMITS"] = "1"
        env["MVK_CONFIG_PREFILL_METAL_COMMAND_BUFFERS"] = "0"
        env["MVK_CONFIG_FULL_IMAGE_VIEW_SWIZZLE"] = "1"
        env["MVK_CONFIG_FAST_MATH_ENABLED"] = "0"
        env["MVK_CONFIG_RESUME_LOST_DEVICE"] = "1"

        check("MVK allow metal events is disabled (0)", env["MVK_CONFIG_ALLOW_METAL_EVENTS"] == "0")
        check("MVK semaphore support style is single queue (0)", env["MVK_CONFIG_VK_SEMAPHORE_SUPPORT_STYLE"] == "0")
        check("MVK synchronous queue submits is enabled (1)", env["MVK_CONFIG_SYNCHRONOUS_QUEUE_SUBMITS"] == "1")
        check("MVK prefill command buffers is disabled (0)", env["MVK_CONFIG_PREFILL_METAL_COMMAND_BUFFERS"] == "0")
        check("MVK full image view swizzle is enabled (1)", env["MVK_CONFIG_FULL_IMAGE_VIEW_SWIZZLE"] == "1")
        check("MVK fast math is disabled (0)", env["MVK_CONFIG_FAST_MATH_ENABLED"] == "0")
        check("MVK resume lost device is enabled (1)", env["MVK_CONFIG_RESUME_LOST_DEVICE"] == "1")

        // --- Test 2: FFmpeg Filter Threading Arguments ---
        func mockBuildFFmpegArgs(inputPath: String, filterGraph: String) -> [String] {
            var args: [String] = []
            args.append(contentsOf: ["-init_hw_device", "vulkan=vk:0", "-filter_hw_device", "vk"])
            args.append(contentsOf: ["-y"])
            args.append(contentsOf: ["-threads", "0"])
            args.append(contentsOf: ["-filter_threads", "1"])
            args.append(contentsOf: ["-filter_complex_threads", "1"])
            args.append(contentsOf: ["-i", inputPath])
            args.append(contentsOf: ["-vf", filterGraph])
            return args
        }

        let testArgs = mockBuildFFmpegArgs(inputPath: "/tmp/in.mp4", filterGraph: "hwupload,libplacebo,hwdownload")
        check("FFmpeg arguments contain -filter_threads 1",
              testArgs.contains("-filter_threads") &&
              testArgs[testArgs.firstIndex(of: "-filter_threads")! + 1] == "1")
        check("FFmpeg arguments contain -filter_complex_threads 1",
              testArgs.contains("-filter_complex_threads") &&
              testArgs[testArgs.firstIndex(of: "-filter_complex_threads")! + 1] == "1")
        check("FFmpeg arguments preserve -threads 0 for decode/encode",
              testArgs.contains("-threads") &&
              testArgs[testArgs.firstIndex(of: "-threads")! + 1] == "0")

        // --- Test 3: RawVideoFrameSource Shader Path Escaping ---
        func mockStreamArgs(shaderPath: String) -> [String] {
            let escapedPath = shaderPath.replacingOccurrences(of: "'", with: "'\\''")
            let vf = "hwupload,libplacebo=custom_shader_path='\(escapedPath)':format=p010le,hwdownload,format=p010le"
            var a = ["-init_hw_device", "vulkan=vk:0", "-filter_hw_device", "vk", "-y", "-filter_threads", "1"]
            a += ["-i", "/tmp/in.mp4", "-vf", vf, "-pix_fmt", "bgra", "-f", "rawvideo", "pipe:1"]
            return a
        }

        let pathWithSpaces = "/Applications/Anime4K Upscaler.app/Contents/Resources/Shaders/Anime4K_Restore_CNN_VL.glsl"
        let streamArgs = mockStreamArgs(shaderPath: pathWithSpaces)
        let vfArg = streamArgs[streamArgs.firstIndex(of: "-vf")! + 1]
        check("vf argument single-quotes shader path", vfArg.contains("custom_shader_path='\(pathWithSpaces)'"))
        check("streamArgs contains -filter_threads 1",
              streamArgs.contains("-filter_threads") &&
              streamArgs[streamArgs.firstIndex(of: "-filter_threads")! + 1] == "1")

        // --- Test 4: Triple Buffer Ring Index Cycling ---
        var slotIndex = 0
        let slotCount = 3
        var visitedSlots: [Int] = []
        for _ in 0..<6 {
            let current = slotIndex
            visitedSlots.append(current)
            slotIndex = (slotIndex + 1) % slotCount
        }
        check("Triple buffer ring cycles [0, 1, 2, 0, 1, 2]", visitedSlots == [0, 1, 2, 0, 1, 2])

        print("\n\(passed) passed, \(failed) failed\n")
        if failed > 0 { exit(1) }
    }
}
